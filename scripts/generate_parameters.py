#!/usr/bin/env python3
"""Regenerate C++ control metadata from the same photographed-preset bank as the UI."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Resources/presets.json').read_text())
quote=lambda s: json.dumps(s,ensure_ascii=True)
lines=['// Generated by scripts/generate_parameters.py. Do not edit by hand.','#pragma once','#include <array>','struct ParamSpec {const char* id; const char* name; const char* labels; float min,max,step,initial,x,y,size,start,end; bool toggle;};',f'inline constexpr std::array<ParamSpec,{len(data["parameters"])}> specs={{{{']
for p in data['parameters']:
    labels={'source':['LINE','MIC'],'attack':['FAST','MED FAST','MEDIUM','MED SLOW','SLOW'],'release':['FAST','MED FAST','MEDIUM','MED SLOW','SLOW'],'meter':['LINE IN / G-R','PREOUT','EQ OUT','D-S'],'deFreq':['3K','6K','9K','12K','LIMIT 10:1']}.get(p['id'],p.get('labels',[]))
    vals=[quote(p['id']),quote(p['name']),quote('|'.join(labels))]+[f'{float(p[k]):.6f}f' for k in ['min','max','step','default','x','y','size','start','end']]+[str(p['toggle']).lower()]
    lines.append('{'+','.join(vals)+'},')
lines+=['}};']
output=root/'Source/Parameters.h'
content='\n'.join(lines)+'\n'
if not output.exists() or output.read_text()!=content:
    output.write_text(content)
