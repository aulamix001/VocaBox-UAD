#!/usr/bin/env python3
"""Sync the designed bank and CSV from Resources/presets.json, without rendering assets."""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'Resources/presets.json').read_text())
bank = data['presets']
assert len(bank) == 100, 'Expected 100 factory presets'
assert len({p['id'] for p in bank}) == len(bank)
assert len({p['name'] for p in bank}) == len(bank)
for preset in bank:
    assert set(preset['settings']) == {p['id'] for p in data['parameters']}
    for spec in data['parameters']:
        value = preset['settings'][spec['id']]
        assert spec['min'] <= value <= spec['max'], (preset['name'], spec['id'])
        if spec['step']:
            assert abs((value - spec['min']) / spec['step'] - round((value - spec['min']) / spec['step'])) < 1e-6
    assert preset['params'] == preset['settings']
start = '// BEGIN STUDIO PRESETS (generated by scripts/sync_factory_presets.py)'
end = '// END STUDIO PRESETS'
html = (ROOT / 'voxbox.html').read_text()
block = start + '\nlibrary.push(...' + json.dumps(bank[50:], ensure_ascii=False, separators=(',', ':')) + ');\n' + end
html, count = re.subn(re.escape(start) + r'.*?' + re.escape(end), lambda _: block, html, flags=re.S)
assert count == 1
(ROOT / 'voxbox.html').write_text(html)
with (ROOT / 'Resources/PRESET_MAP.csv').open('w', encoding='utf-8-sig', newline='') as out:
    ids = [p['id'] for p in data['parameters']]
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(['Preset', 'Tags', *ids])
    for p in bank:
        writer.writerow([p['name'], ' | '.join(p['tags']), *[p['settings'][k] for k in ids]])
print('100 presets: complete, unique IDs/names, valid parameter ranges/steps; HTML and CSV synchronized.')
